#!/usr/bin/env python3
"""Builds src/emoji_data.c: every Noto Color Emoji image, small and compressed.

    python3 tools/emoji/make_emoji.py NOTO_EMOJI_CHECKOUT [SIZE]

NOTO_EMOJI_CHECKOUT is a checkout of https://github.com/googlefonts/noto-emoji
(tag v2026-09-24-unicode18_0) with 2D/png/72 and third_party/region-flags/png.

Each emoji (single characters, skin tones, ZWJ sequences, keycaps, flags) becomes
a SIZE x SIZE image with its own palette of up to 32 colours: one byte with the
colour count, the palette (RGB565 little-endian + alpha per colour), then the
LZ4-compressed colour index of every pixel.
The firmware maps each sequence to one Private Use character (U+F0000 + index)
and draws the image for it (see src/emoji.cpp).
"""
import os
import sys

import lz4.block
from PIL import Image

src, size = sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 20
out_c = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'emoji_data.c')

FE0F = 0xFE0F
entries = {}  # tuple of codepoints (no FE0F) -> png path

png_dir = os.path.join(src, '2D', 'png', '72')
for name in os.listdir(png_dir):
    if not name.startswith('emoji_u') or not name.endswith('.png'):
        continue
    cps = tuple(int(h, 16) for h in name[7:-4].split('_') if int(h, 16) != FE0F)
    entries[cps] = os.path.join(png_dir, name)

# Flags: two letters -> regional indicators; GB-ENG / GB-SCT / GB-WLS -> tag sequences.
flag_dir = os.path.join(src, 'third_party', 'region-flags', 'png')
for name in os.listdir(flag_dir):
    code = name[:-4]
    if len(code) == 2 and code.isalpha():
        cps = tuple(0x1F1E6 + ord(ch) - ord('A') for ch in code)
    elif code in ('GB-ENG', 'GB-SCT', 'GB-WLS'):
        cps = (0x1F3F4,) + tuple(0xE0000 + ord(ch) for ch in code.replace('-', '').lower()) + (0xE007F,)
    else:
        continue
    entries.setdefault(cps, os.path.join(flag_dir, name))

seqs = sorted(entries)  # sorted: the firmware binary-searches on the first codepoint


def encode(path):
    img = Image.open(path).convert('RGBA')
    w, h = img.size
    scale = size / max(w, h)  # fit (flags are wider than tall), centred on a square
    img = img.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    canvas.paste(img, ((size - img.width) // 2, (size - img.height) // 2))
    q = canvas.quantize(colors=32, method=Image.Quantize.FASTOCTREE)
    used = len(q.getcolors())
    pal = q.getpalette(rawmode='RGBA')[:4 * used]
    out = bytearray([used])
    for i in range(used):
        r, g, b, a = pal[4 * i:4 * i + 4]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        out += bytes((v & 0xFF, v >> 8, a))
    idx = bytes(q.tobytes())
    assert max(idx) < used
    return bytes(out) + lz4.block.compress(idx, store_size=False, mode='high_compression')


blob, offsets = bytearray(), []
for s in seqs:
    offsets.append(len(blob))
    blob += encode(entries[s])
offsets.append(len(blob))

cp_list, seq_start = [], []
for s in seqs:
    seq_start.append(len(cp_list))
    cp_list += s
seq_start.append(len(cp_list))


def rows(values, per_line, fmt):
    for i in range(0, len(values), per_line):
        yield '  ' + ','.join(fmt(v) for v in values[i:i + per_line]) + ','


with open(out_c, 'w') as f:
    f.write('// Generated by tools/emoji/make_emoji.py from Noto Color Emoji (Apache-2.0 / OFL-1.1).\n')
    f.write('// Do not edit.\n#include <stdint.h>\n\n')
    f.write(f'const uint16_t emoji_size = {size};\nconst uint32_t emoji_count = {len(seqs)};\n\n')
    f.write('// Codepoints of every sequence, back to back; sequence i is emoji_cps[emoji_seq[i] .. emoji_seq[i+1]).\n')
    f.write('const uint32_t emoji_cps[] = {\n' + '\n'.join(rows(cp_list, 12, hex)) + '\n};\n')
    f.write('const uint16_t emoji_seq[] = {\n' + '\n'.join(rows(seq_start, 20, str)) + '\n};\n\n')
    f.write('// Palette + LZ4 index block; image i is emoji_lz4[emoji_at[i] .. emoji_at[i+1]).\n')
    f.write('const uint32_t emoji_at[] = {\n' + '\n'.join(rows(offsets, 16, str)) + '\n};\n')
    f.write('const uint8_t emoji_lz4[] = {\n' + '\n'.join(rows(list(blob), 40, str)) + '\n};\n')

print(f'{len(seqs)} emoji, {len(blob) / 1024:.0f} KiB of images, {len(cp_list)} codepoints')
