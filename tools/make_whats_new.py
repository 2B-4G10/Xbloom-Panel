#!/usr/bin/env python3
"""Turns the pending release notes (.github/release-notes.md) into include/whats_new.h:
the highlights the panel shows once after it updates. One line per top-level bullet,
the emoji and bold title only ("- 🛜 **One-tap updates.** ..." -> "🛜 One-tap updates")."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
notes = (root / ".github/release-notes.md").read_text(encoding="utf-8")
notes = re.sub(r"<!--.*?-->", "", notes, flags=re.S)
items = []
for line in notes.splitlines():
    m = re.match(r"^- (.*)", line)  # top-level bullets only
    if not m:
        continue
    text = m.group(1)
    b = re.match(r"^(\W*?)\s*\*\*(.+?)\*\*", text)
    if b:
        text = (b.group(1).strip() + " " + b.group(2)).strip()
    else:
        text = re.sub(r"\*\*|`|\[|\]\([^)]*\)", "", text)
        text = re.split(r"(?<=[.!?])\s", text)[0]
    text = text.split(", ")[0].rstrip(".:").strip()  # one short line each
    if len(text) > 46:
        text = text[:44].rsplit(" ", 1)[0] + "..."
    if text and not text.lower().startswith(("last time by hand", "panel restarting")):
        items.append(text)
items = items[:5]
c = "\\n".join(i.replace("\\", "\\\\").replace('"', '\\"') for i in items)
out = root / "include/whats_new.h"
out.write_text(
    "// Generated by tools/make_whats_new.py from .github/release-notes.md at build time.\n"
    "// The highlights shown once after an update; empty when there are none.\n#pragma once\n"
    f'#define WHATS_NEW "{c}"\n', encoding="utf-8")
print(f"whats_new.h: {len(items)} highlight(s)")
for i in items:
    print("  ", i)
